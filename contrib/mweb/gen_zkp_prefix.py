#!/usr/bin/env python3
"""Generate src/mweb_zkp_prefix.h.

BitcoinOil links two copies of libsecp256k1: its own (src/secp256k1) and
Litecoin's, which carries the generator, commitment, bulletproofs and aggsig
modules that MWEB needs (src/secp256k1-zkp). The header renames every
secp256k1_* identifier of the second copy so both can live in one binary.
Run from the repository root after updating src/secp256k1-zkp.
"""
import pathlib, re
root = pathlib.Path('src/secp256k1-zkp')
names = set()
for f in sorted(root.rglob('*')):
    if f.suffix in ('.h', '.c'):
        names.update(re.findall(r'\bsecp256k1_[A-Za-z0-9_]+\b', f.read_text(errors='replace')))
out = ['// Generated by contrib/mweb/gen_zkp_prefix.py. Do not edit.', '#ifndef BITCOINOIL_MWEB_ZKP_PREFIX_H', '#define BITCOINOIL_MWEB_ZKP_PREFIX_H']
out += [f'#define {n} btcomw_{n}' for n in sorted(names)]
out += ['#endif // BITCOINOIL_MWEB_ZKP_PREFIX_H', '']
pathlib.Path('src/mweb_zkp_prefix.h').write_text('\n'.join(out))
print(len(names), 'identifiers')
